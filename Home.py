import streamlit as st, pandas as pd
from data import load, header, roster
st.set_page_config(layout="wide")
header("IAA Career Services Overview")
d = load()
d["T"] = pd.to_datetime(d["Timestamp"], format="%m/%d/%y %H:%M")
r = roster()
n = d[~d["UnityID"].isin(r["UnityID"])].drop_duplicates("UnityID")
r = pd.concat([r, pd.DataFrame({"Last, First Name": n["Last Name"] + ", " + n["First Name"], "UnityID": n["UnityID"]})])
x = d[d["Level"] == "Interview"].groupby(["UnityID", "Interview Round "]).size().unstack(fill_value=0)
s1 = x[(x["First Round"] >= 3) & (x["Second Round"] == 0)].index
fl = pd.concat([r[~r["UnityID"].isin(d["UnityID"])].assign(Flag="No entries reported"), r[r["UnityID"].isin(s1)].assign(Flag="3+ first rounds, no second round")])
ac = d[d["Level"] == "Acceptance"].copy()
ac["Base"] = ac["Final Salary"].str.replace(r"[^\d]", "", regex=True).astype(float)
q = st.columns(3)
q[0].metric("Placement rate", f"{ac['UnityID'].nunique() / len(r):.0%}")
q[1].metric("Late-round to offer rate", f"{(d['Level'] == 'Offer').sum() / d['Interview Round '].isin(['Second Round', 'Final Round']).sum():.0%}")
q[2].metric("Median base salary", f"${ac['Base'].median():,.0f}")
st.subheader("Students needing support")
st.dataframe(fl, hide_index=True)
k = st.columns(4)
k[0].metric("Students reported", f"{d['UnityID'].nunique()} of {len(r)}")
k[1].metric("Interviews", (d["Level"] == "Interview").sum())
k[2].metric("Offers", (d["Level"] == "Offer").sum())
k[3].metric("Accepted", (d["Level"] == "Acceptance").sum())
a, b = st.columns(2)
a.subheader("Activity by month")
a.line_chart(d.groupby([d["T"].dt.strftime("%Y-%m"), "Level"]).size().unstack(fill_value=0), color=["#C8102E", "#111111", "#999999"])
b.subheader("Top 10 employers by interviews")
b.bar_chart(d[d["Level"] == "Interview"]["Company"].value_counts().head(10), color="#C8102E", horizontal=True, sort=False)
c, e = st.columns(2)
c.subheader("Where students hear about jobs")
c.bar_chart(d["How did you hear about the job?"].value_counts(), color="#111111", horizontal=True, sort=False)
e.subheader("Average base salary by position")
e.bar_chart(ac.groupby("Position")["Base"].mean().sort_values(ascending=False), color="#C8102E", sort=False)
rd = d["Interview Round "].value_counts()
fn = pd.Series({"1 Screening": rd["Recruiter Screening"], "2 First": rd["First Round"], "3 Second": rd["Second Round"], "4 Final": rd["Final Round"], "5 Offer": (d["Level"] == "Offer").sum(), "6 Accepted": (d["Level"] == "Acceptance").sum()})
st.subheader("Recruiting funnel")
st.bar_chart(fn, color="#C8102E")